class JobModelTests(TestCase):
    def setUp(self):
        self.category = JobCategory.objects.create(name='Software Engineering')
        self.company = Company.objects.create(name='Acme Corp', industry='Tech')
        self.skill = Skill.objects.create(name='Python')
        self.job = JobPosting.objects.create(
            title='Backend Engineer', company=self.company, category=self.category,
            description='Build things.', location='Remote', salary_min=90000, salary_max=120000,
        )

    def test_slug_autogenerated(self):
        self.assertTrue(self.job.slug)
        self.assertIn('backend-engineer', self.job.slug)

    def test_unique_slug_on_duplicate_title(self):
        job2 = JobPosting.objects.create(
            title='Backend Engineer', company=self.company, category=self.category,
            description='Another one.', location='Remote',
        )
        self.assertNotEqual(self.job.slug, job2.slug)

    def test_salary_display(self):
        self.assertIn('90,000', self.job.salary_display)
        self.assertIn('120,000', self.job.salary_display)

    def test_salary_display_no_salary(self):
        job = JobPosting.objects.create(
            title='Mystery Role', company=self.company, category=self.category,
            description='?', location='Remote',
        )
        self.assertEqual(job.salary_display, 'Not disclosed')

    def test_job_skill_weight(self):
        js = JobSkill.objects.create(job=self.job, skill=self.skill, importance='required')
        self.assertEqual(js.weight, 3)
        js.importance = 'nice_to_have'
        self.assertEqual(js.weight, 1)

    def test_company_active_job_count(self):
        self.assertEqual(self.company.active_job_count, 1)
        JobPosting.objects.create(
            title='Inactive Role', company=self.company, category=self.category,
            description='...', location='Remote', is_active=False,
        )
        self.assertEqual(self.company.active_job_count, 1)


class JobViewTests(TestCase):
    def setUp(self):
        self.client = Client()
        self.category = JobCategory.objects.create(name='Data Science & Analytics')
        self.company = Company.objects.create(name='DataCorp')
        self.skill = Skill.objects.create(name='SQL')
        self.job = JobPosting.objects.create(
            title='Data Analyst', company=self.company, category=self.category,
            description='Analyze data.', location='New York, NY', salary_min=70000, salary_max=95000,
        )
        JobSkill.objects.create(job=self.job, skill=self.skill, importance='required')
        self.user = User.objects.create_user(username='tester', password='testpass123')

    def test_home_page_loads(self):
        response = self.client.get(reverse('jobs:home'))
        self.assertEqual(response.status_code, 200)
        self.assertContains(response, 'Data Analyst')

    def test_job_list_loads(self):
        response = self.client.get(reverse('jobs:job_list'))
        self.assertEqual(response.status_code, 200)
        self.assertContains(response, 'Data Analyst')

    def test_job_list_keyword_filter(self):
        response = self.client.get(reverse('jobs:job_list'), {'q': 'Data Analyst'})
        self.assertContains(response, 'Data Analyst')
        response = self.client.get(reverse('jobs:job_list'), {'q': 'Nonexistent Role XYZ'})
        self.assertNotContains(response, 'Data Analyst')

    def test_job_list_location_filter(self):
        response = self.client.get(reverse('jobs:job_list'), {'location': 'New York'})
        self.assertContains(response, 'Data Analyst')
        response = self.client.get(reverse('jobs:job_list'), {'location': 'Nowhere'})
        self.assertNotContains(response, 'Data Analyst')

    def test_job_detail_increments_views(self):
        initial_views = self.job.views_count
        response = self.client.get(self.job.get_absolute_url())
        self.assertEqual(response.status_code, 200)
        self.job.refresh_from_db()
        self.assertEqual(self.job.views_count, initial_views + 1)

    def test_job_detail_404_for_bad_slug(self):
        response = self.client.get('/jobs/does-not-exist/')
        self.assertEqual(response.status_code, 404)

    def test_save_job_requires_login(self):
        response = self.client.post(reverse('jobs:toggle_save_job', args=[self.job.slug]))
        self.assertEqual(response.status_code, 302)
        self.assertIn('/accounts/login/', response.url)

    def test_save_and_unsave_job(self):
        self.client.login(username='tester', password='testpass123')
        response = self.client.post(reverse('jobs:toggle_save_job', args=[self.job.slug]))
        self.assertEqual(response.status_code, 302)
        self.assertTrue(SavedJob.objects.filter(user=self.user, job=self.job).exists())

        response = self.client.post(reverse('jobs:toggle_save_job', args=[self.job.slug]))
        self.assertFalse(SavedJob.objects.filter(user=self.user, job=self.job).exists())

    def test_apply_to_job(self):
        self.client.login(username='tester', password='testpass123')
        response = self.client.post(reverse('jobs:apply_to_job', args=[self.job.slug]))
        self.assertEqual(response.status_code, 302)
        self.assertTrue(Application.objects.filter(user=self.user, job=self.job).exists())

    def test_apply_twice_does_not_duplicate(self):
        self.client.login(username='tester', password='testpass123')
        self.client.post(reverse('jobs:apply_to_job', args=[self.job.slug]))
        self.client.post(reverse('jobs:apply_to_job', args=[self.job.slug]))
        self.assertEqual(Application.objects.filter(user=self.user, job=self.job).count(), 1)

    def test_company_detail_page(self):
        response = self.client.get(self.company.get_absolute_url())
        self.assertEqual(response.status_code, 200)
        self.assertContains(response, self.company.name)

